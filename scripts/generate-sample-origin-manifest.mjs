import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectDirectory = resolve(scriptDirectory, "..");
const fixtureSource = resolve(projectDirectory, "src", "domain", "fixtures.ts");
const samplesDirectory = resolve(projectDirectory, "public", "samples");
const manifestPath = process.env.SAMPLE_ORIGIN_MANIFEST_PATH
  ? resolve(process.env.SAMPLE_ORIGIN_MANIFEST_PATH)
  : resolve(
      projectDirectory,
      "src",
      "server",
      "security",
      "sample-origin-manifest.ts",
    );
const checkMode = process.argv.includes("--check");

async function loadSyntheticFixtures() {
  const source = await readFile(fixtureSource, "utf8");
  const compiled = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2022,
    },
  }).outputText;
  const moduleUrl = `data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`;
  return (await import(moduleUrl)).syntheticFixtures;
}

function sha256Hex(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function renderManifest(entries) {
  const lines = entries.map(
    ([filename, digest]) =>
      `  ${JSON.stringify(filename)}:\n    ${JSON.stringify(digest)},`,
  );
  return [
    "// Generated by scripts/generate-sample-origin-manifest.mjs. Do not edit manually.",
    "// A match establishes byte equality with a committed synthetic sample only.",
    "export const sampleOriginManifest: Readonly<Record<string, string>> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

function normalizeLineEndings(content) {
  return content.replace(/\r\n/g, "\n");
}

const fixtures = await loadSyntheticFixtures();
const entries = await Promise.all(
  fixtures
    .toSorted((left, right) => left.id.localeCompare(right.id))
    .map(async (fixture) => [
      fixture.filename,
      sha256Hex(await readFile(resolve(samplesDirectory, fixture.filename))),
    ]),
);
const content = renderManifest(entries);

if (checkMode) {
  let existing = null;
  try {
    existing = await readFile(manifestPath, "utf8");
  } catch {
    // A missing manifest is drift and the check must not create it.
  }
  if (
    existing === null ||
    normalizeLineEndings(existing) !== normalizeLineEndings(content)
  ) {
    console.error("sample_origin_manifest_drift");
    process.exitCode = 1;
  }
} else {
  await mkdir(dirname(manifestPath), { recursive: true });
  await writeFile(manifestPath, content);
}
